// Bundles files the server reads while handling requests into a module,
// because Workers have no filesystem at request time. Run it on install,
// before `dev` and before `build`, and git-ignore the output. List in SOURCES
// what the app's loaders read; the loaders then import the module.
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const outFile = path.join(root, "lib/generated/server-content.ts");

// export name -> a directory of text files, or one file (base64 for binaries)
const SOURCES = {
  posts: { dir: "content/posts", ext: [".md", ".mdx"] },
  // ogFont: { file: "node_modules/<font-package>/<font>.ttf", base64: true },
};

const out = ["// Generated by generate-server-content.mjs. Do not edit."];
for (const [name, src] of Object.entries(SOURCES)) {
  if (src.dir) {
    const dir = path.join(root, src.dir);
    const files = (await readdir(dir, { recursive: true }))
      .filter((f) => src.ext.some((e) => f.endsWith(e)))
      .sort();
    const entries = await Promise.all(
      files.map(async (f) => ({ path: f, source: await readFile(path.join(dir, f), "utf8") }))
    );
    out.push(`export const ${name}: readonly { path: string; source: string }[] = ${JSON.stringify(entries)};`);
  } else {
    const buf = await readFile(path.join(root, src.file));
    out.push(`export const ${name}: string = ${JSON.stringify(src.base64 ? buf.toString("base64") : buf.toString("utf8"))};`);
  }
}
await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(outFile, out.join("\n") + "\n");
console.log(`server content: ${Object.keys(SOURCES).length} source(s) -> ${path.relative(root, outFile)}`);
